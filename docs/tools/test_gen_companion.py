import gen_companion
from gen_companion import DocumentProblem, build, github_slug, listing_name, page_name

PROGRAM = "line 1\n    line 2\n    line 3\nline 4\nline 5\nline 6\nline 7\n"


class WithRepository(unittest.TestCase):
    """Gives a check its own folder that stands for the repository."""

    def setUp(self):
        folder = tempfile.TemporaryDirectory(prefix="stargate-docs-test-")
        self.addCleanup(folder.cleanup)
        self.repo = Path(folder.name) / "repo"
        self.repo.mkdir()

    def write(self, name, text):
        path = self.repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text if isinstance(text, bytes) else text.encode("utf-8"))
        return path

    def build(self, text, **options):
        return build(text, self.repo / "study.md", self.repo, **options)


