GUIDE = """\
# Guide

Intro.

## Contents

- [1. Alpha](#1-alpha)
- [2. Beta](#2-beta)

## 1. Alpha

Text of alpha.

### Details

More.

## 2. Beta

Text of beta.
"""


class Pages(WithRepository):
    def test_every_part_is_a_page_and_the_start_page_keeps_the_contents(self):
        pages, document_map, notes = self.build(GUIDE)
        self.assertEqual(sorted(pages), ["1-alpha.md", "2-beta.md", "index.md"])
        self.assertEqual(notes, [])
        self.assertIn("Intro.", pages["index.md"])
        self.assertIn("- [1. Alpha](#1-alpha)", pages["index.md"])
        self.assertNotIn("Text of alpha.", pages["index.md"])
        self.assertEqual(document_map["title"], "Guide")
        self.assertEqual(document_map["document"], "study.md")

    def test_a_page_starts_with_one_heading_sign_and_the_others_follow(self):
        pages, _, _ = self.build(GUIDE)
        lines = pages["1-alpha.md"].splitlines()
        self.assertTrue(lines[0].startswith("% Generated by tools/gen_companion.py from study.md"))
        self.assertEqual(lines[2], "# 1. Alpha")
        self.assertIn("## Details", lines)

    def test_the_first_line_says_where_a_line_is_in_the_document(self):
        pages, document_map, _ = self.build(GUIDE)
        self.assertEqual(document_map["pages"]["1-alpha"], {"slugs": ["1-alpha", "details"], "first_line": 10})
        self.assertIn("(line n here is line n + 7 there)", pages["1-alpha.md"])
        # Line 3 of the page is its heading, which is line 10 of the document.
        self.assertEqual(pages["1-alpha.md"].splitlines()[2], "# " + GUIDE.splitlines()[9][3:])

    def test_the_list_of_pages_is_hidden_when_the_text_links_to_each_of_them(self):
        pages, _, _ = self.build(GUIDE)
        self.assertIn("```{toctree}\n:hidden:\n\n/1-alpha\n/2-beta\n```", pages["index.md"])
        self.assertNotIn("This part continues", pages["index.md"])

    def test_the_list_of_pages_is_shown_when_the_text_does_not_link_to_them(self):
        pages, _, _ = self.build("# Guide\n\nIntro.\n\n## One\n\nText.\n\n## Two\n\nText.\n")
        self.assertIn("**This part continues on these pages:**\n\n```{toctree}\n:maxdepth: 1\n\n/one\n/two\n```",
                      pages["index.md"])

    def test_names_that_sphinx_uses_itself_are_avoided(self):
        pages, _, _ = self.build("# Guide\n\n## Search\n\nText.\n\n## Index\n\nText.\n\n## Files\n\nText.\n")
        self.assertEqual(sorted(pages), ["files-2.md", "index-2.md", "index.md", "search-2.md"])

    def test_where_every_heading_went(self):
        _, document_map, _ = self.build(GUIDE)
        self.assertEqual(document_map["anchors"]["guide"], {"page": "index", "id": "guide", "title": "Guide", "trail": ""})
        self.assertEqual(document_map["anchors"]["contents"]["page"], "index")
        self.assertEqual(document_map["anchors"]["1-alpha"],
                         {"page": "1-alpha", "id": "1-alpha", "title": "1. Alpha", "trail": ""})
        self.assertEqual(document_map["anchors"]["details"],
                         {"page": "1-alpha", "id": "details", "title": "Details", "trail": "1. Alpha"})

    def test_a_heading_inside_a_list_leads_to_the_section_around_it(self):
        _, document_map, _ = self.build(
            "# Guide\n\n## One\n\n- an item\n\n  ### Inside a list\n\n  text\n\n### Sub\n\nText.\n\n## Two\n\nText.\n")
        self.assertEqual(document_map["pages"]["one"]["slugs"], ["one", "sub"])
        self.assertEqual(document_map["anchors"]["inside-a-list"], document_map["anchors"]["one"])

    def test_the_document_needs_exactly_one_title_and_it_comes_first(self):
        for text in ("## Only a part\n\nText.\n", "# One\n\n# Two\n", "## Part\n\n# Title\n", "No heading at all.\n"):
            with self.subTest(text=text):
                with self.assertRaises(DocumentProblem) as raised:
                    self.build(text)
                self.assertIn("needs exactly one title", str(raised.exception))
        with self.assertRaises(DocumentProblem) as raised:
            self.build("# One\n\ntext\n\n# Two\n")
        self.assertIn("(lines 1, 5)", str(raised.exception))


LARGE = """\
# Guide

## Part

Intro of the part.

### Notes

Short notes.

### Pattern 1: First

Body of the first.

### Pattern 2: Second

Body of the second.

## Small

Text.
"""


class LargePages(WithRepository):
    def test_a_page_within_the_limit_stays_whole(self):
        pages, _, _ = self.build(LARGE)
        self.assertEqual(sorted(pages), ["index.md", "part.md", "small.md"])

    def test_a_page_over_the_limit_is_cut_at_its_chapters(self):
        pages, document_map, _ = self.build(LARGE, limit=60)
        self.assertEqual(sorted(pages), ["index.md", "part.md", "part/pattern-1-first.md", "part/pattern-2-second.md",
                                         "small.md"])
        # What stands in front of the first chapter stays on the page of the part.
        self.assertIn("Short notes.", pages["part.md"])
        self.assertNotIn("Body of the first.", pages["part.md"])
        self.assertIn("```{toctree}\n:maxdepth: 1\n\n/part/pattern-1-first\n/part/pattern-2-second\n```", pages["part.md"])
        self.assertEqual(pages["part/pattern-1-first.md"].splitlines()[2], "# Pattern 1: First")
        self.assertEqual(document_map["pages"]["part"]["slugs"], ["part", "notes"])
        self.assertEqual(document_map["anchors"]["pattern-2-second"],
                         {"page": "part/pattern-2-second", "id": "pattern-2-second", "title": "Pattern 2: Second",
                          "trail": "Part"})

    def test_a_section_with_sections_of_its_own_counts_as_a_chapter(self):
        text = "# Guide\n\n## Part\n\n### Notes\n\nShort.\n\n### Big\n\nText.\n\n#### Inner\n\nText.\n\n### Last\n\nText.\n"
        pages, _, _ = self.build(text, limit=40)
        self.assertEqual(sorted(pages), ["index.md", "part.md", "part/big.md", "part/last.md"])
        self.assertIn("## Inner", pages["part/big.md"])

    def test_without_chapters_every_section_gets_a_page(self):
        text = "# Guide\n\n## Part\n\nIntro.\n\n### Notes\n\nSome notes.\n\n### More\n\nSome more.\n"
        pages, _, _ = self.build(text, limit=40)
        self.assertEqual(sorted(pages), ["index.md", "part.md", "part/more.md", "part/notes.md"])

    def test_a_page_without_headings_to_cut_at_stays_large(self):
        pages, _, _ = self.build("# Guide\n\n## Part\n\n" + "A long line of text. " * 20 + "\n", limit=40)
        self.assertEqual(sorted(pages), ["index.md", "part.md"])


class Links(WithRepository):
    def setUp(self):
        super().setUp()
        self.write("src/App/Program.cs", PROGRAM)
        self.write(".env.example", "NAME=value\n")
        self.write("logo.bin", b"\x89PNG\0\0")
        (self.repo / "docs").mkdir()
        self.write("../outside.txt", "not in the repository\n")

    def test_a_linked_file_gets_a_page_that_shows_it(self):
        text = ("# Guide\n\nSee [the program](src/App/Program.cs#L2-L3), [one line](src/App/Program.cs#L4),\n"
                "[the settings](.env.example) and [a site](https://example.org/a?b=1&c=2).\n\n"
                "## Part\n\nAgain [the program](src/App/Program.cs#L2-L3) and [all of it](src/App/Program.cs).\n")
        pages, document_map, notes = self.build(text)
        self.assertEqual(notes, [])
        self.assertEqual(document_map["links"], {"src/App/Program.cs": "src/App/Program.cs", ".env.example": ".env.example"})
        self.assertEqual(document_map["files"], {"src/App/Program.cs": "files/src/App/Program.cs",
                                                 ".env.example": "files/dot-env.example"})
        listing = pages["files/src/App/Program.cs.md"]
        self.assertTrue(listing.startswith("---\norphan: true\n---\n"))
        self.assertIn("# `src/App/Program.cs`", listing)
        self.assertIn("```{source-listing} src/App/Program.cs\n```", listing)
        # Which sections point into the file, and at which lines.
        self.assertIn("- [Guide](#guide): [lines 2–3](#L2-L3), [line 4](#L4)", listing)
        self.assertIn("- [Part](#part): [lines 2–3](#L2-L3)", listing)
        self.assertIn("```{source-listing} .env.example\n```", pages["files/dot-env.example.md"])

    def test_a_link_that_leads_to_no_text_file_is_reported(self):
        for written in ("src/App/Missing.cs", "docs", "logo.bin", "../outside.txt"):
            with self.subTest(link=written):
                pages, document_map, notes = self.build(f"# Guide\n\nText.\n\nSee [this]({written}#L1).\n")
                self.assertEqual(document_map["links"], {written: None})
                self.assertEqual(document_map["files"], {})
                self.assertEqual(sorted(pages), ["index.md"])
                self.assertEqual(notes, [f"line 5: the link ({written}#L1) does not lead to a text file in the "
                                         "repository; it is shown as plain text"])

    def test_a_file_that_is_gone_is_reported_once_however_many_links_name_it(self):
        # Paragraphs on lines 3, 5, 7, ..., 17. A note names the line its paragraph starts on.
        paragraphs = ["# Guide", "See [the notes](NOTES.md) and [a line](NOTES.md#L4), [again](NOTES.md#L4)."]
        paragraphs += [f"This one names [it](NOTES.md#L{number})." for number in range(1, 7)]
        paragraphs += ["Another one: [gone](src/App/Gone.cs#L1). And [the program](src/App/Program.cs#L2)."]
        _, document_map, notes = self.build("\n\n".join(paragraphs) + "\n")
        self.assertEqual(notes, [
            "lines 3, 5, 7, 9, 11 and 2 more: 9 links to NOTES.md do not lead to a text file in the repository; "
            "they are shown as plain text",
            "line 17: the link (src/App/Gone.cs#L1) does not lead to a text file in the repository; it is shown as plain text"])
        self.assertEqual(document_map["links"], {"NOTES.md": None, "src/App/Gone.cs": None,
                                                 "src/App/Program.cs": "src/App/Program.cs"})
        # Several links on one line, and nothing else: "line", not "lines".
        _, _, notes = self.build("# Guide\n\n[a](two%20words.md) and [b](two%20words.md#L2).\n")
        self.assertEqual(notes, ["line 3: 2 links to two words.md do not lead to a text file in the repository; "
                                 "they are shown as plain text"])

    def test_a_link_past_the_end_of_a_file_is_reported(self):
        _, _, notes = self.build("# Guide\n\nSee [this](src/App/Program.cs#L6-L40).\n")
        self.assertEqual(notes, ["line 3: the link (src/App/Program.cs#L6-L40) points past the end of the file, "
                                 "which has 7 lines"])

    def test_a_file_that_is_too_large_gets_no_page(self):
        self.write("big.txt", "x" * (gen_companion.LARGEST_FILE + 1))
        _, document_map, notes = self.build("# Guide\n\nSee [this](big.txt).\n")
        self.assertEqual(document_map["files"], {})
        self.assertEqual(len(notes), 1)

    def test_a_path_from_the_root_of_the_repository_and_a_path_with_percent_signs(self):
        self.write("docs/two words.md", "text\n")
        _, document_map, notes = self.build("# Guide\n\n[a](/src/App/Program.cs) and [b](docs/two%20words.md).\n")
        self.assertEqual(notes, [])
        self.assertEqual(document_map["links"], {"/src/App/Program.cs": "src/App/Program.cs",
                                                 "docs/two%20words.md": "docs/two words.md"})


def excerpt(lines, code, before=""):
    return ("# Guide\n\n## Part\n\n" + before
            + f"**[`src/App/Program.cs`](src/App/Program.cs#L2-L3)** · {lines}\n\n```csharp\n{code}```\n")


class Excerpts(WithRepository):
    def setUp(self):
        super().setUp()
        self.write("src/App/Program.cs", PROGRAM)

    def test_an_excerpt_that_matches_its_file_is_left_alone(self):
        # The file indents these lines and the excerpt does not: that is not a difference.
        _, document_map, notes = self.build(excerpt("lines 2–3", "line 2\nline 3\n"))
        self.assertEqual((document_map["stale"], notes), ({}, []))

    def test_an_excerpt_that_no_longer_matches_is_marked(self):
        _, document_map, notes = self.build(excerpt("lines 2–3", "line 2\nline three\n"))
        self.assertEqual(list(document_map["stale"]), ["part"])
        self.assertEqual(list(document_map["stale"]["part"]), ["0"])
        self.assertTrue(document_map["stale"]["part"]["0"].startswith(
            "This excerpt no longer matches src/App/Program.cs (lines 2–3)."))
        self.assertEqual(notes, ["line 5: the excerpt of src/App/Program.cs (lines 2–3) no longer matches the file"])

    def test_the_file_changing_makes_an_excerpt_stale(self):
        text = excerpt("lines 2–3", "line 2\nline 3\n")
        self.assertEqual(self.build(text)[1]["stale"], {})
        self.write("src/App/Program.cs", "a new first line\n" + PROGRAM)
        self.assertEqual(list(self.build(text)[1]["stale"]), ["part"])

    def test_lines_left_out_are_allowed_when_the_caption_names_both_ranges(self):
        code = "line 2\nline 3\n// ... lines 4–5 omitted ...\nline 6\nline 7\n"
        _, document_map, notes = self.build(excerpt("lines 2–3 and 6–7", code))
        self.assertEqual((document_map["stale"], notes), ({}, []))
        _, document_map, _ = self.build(excerpt("lines 2–3 and 6–7", code.replace("line 7", "line seven")))
        self.assertIn("(lines 2–3 and lines 6–7)", document_map["stale"]["part"]["0"])

    def test_one_line_and_empty_lines_around_the_code(self):
        _, document_map, _ = self.build(excerpt("line 4", "\nline 4\n\n"))
        self.assertEqual(document_map["stale"], {})

    def test_the_excerpt_is_named_by_its_place_among_the_code_blocks_of_its_page(self):
        other = "```text\nanother block\n```\n\n"
        _, document_map, _ = self.build(excerpt("lines 2–3", "changed\n", before=other))
        self.assertEqual(list(document_map["stale"]["part"]), ["1"])

    def test_a_code_block_without_a_caption_is_not_compared(self):
        _, document_map, notes = self.build("# Guide\n\n## Part\n\n```csharp\nnot in any file\n```\n")
        self.assertEqual((document_map["stale"], notes), ({}, []))

    def test_a_row_that_gives_the_number_of_lines_of_a_file(self):
        table = "# Guide\n\n| File | Path | Lines |\n|---|---|---|\n| Program | [`src/App/Program.cs`](src/App/Program.cs) | {} |\n"
        self.assertEqual(self.build(table.format(7))[2], [])
        self.assertEqual(self.build(table.format(9))[2],
                         ["line 5: src/App/Program.cs has 7 lines now; the document says 9. "
                          "Line numbers in links to it may be off"])


def names():
    found = code_names.CodeNames()
    found.add_type("Shop.Orders.Order")
    found.add_member("Shop.Orders.Order.Close")
    found.add_type("Shop.Orders.Result-1")
    return found


MENTIONS = """\
# Guide

`Order` is named here once.

## Back end

`Order`, `Order.Close()` and again `Order`. Also `Result<Order>`, a [`Order` in a link](src/App/Order.cs)
and `NotAName`.

### A heading with `Order`

Nothing else.

## Front end

`Order` means the TypeScript type here. See [a](src/Web/order.ts) and [b](src/Web/order.ts#L1).

### Deeper

`Order` and `Order.Close()` again, and `Result<T>`.
"""


class Mentions(WithRepository):
    def setUp(self):
        super().setUp()
        self.write("src/App/Order.cs", "public sealed class Order { }\n")
        self.write("src/Web/order.ts", "export interface Order {\n  id: string;\n}\nexport type Other = string;\nconst x = 1;\n")

    def test_sections_about_the_web_app_are_found_by_the_files_they_link_to(self):
        _, document_map, _ = self.build(MENTIONS, names=names())
        self.assertEqual(document_map["typescript"], {"names": ["Order", "Other"], "sections": ["front-end", "deeper"]})

    def test_which_section_names_which_type_and_how_often(self):
        _, document_map, _ = self.build(MENTIONS, names=names())
        self.assertEqual(document_map["mentions"], {
            # A member counts for its type. A name in a heading or inside a link does not count,
            # and in a section about the web app "Order" is the TypeScript type.
            "Shop.Orders.Order": [["guide", 1], ["back-end", 3]],
            # Result is no TypeScript type, so it counts in every section.
            "Shop.Orders.Result-1": [["back-end", 1], ["deeper", 1]],
        })

    def test_without_names_nothing_is_counted(self):
        _, document_map, _ = self.build(MENTIONS)
        self.assertEqual(document_map["mentions"], {})


class Main(unittest.TestCase):
    """main() writes the files, and decides what happens when the document cannot be used."""

    def setUp(self):
        folder = tempfile.TemporaryDirectory(prefix="stargate-docs-test-")
        self.addCleanup(folder.cleanup)
        root = Path(folder.name)
        self.document = root / "repo" / "study.md"
        self.document.parent.mkdir()
        self.pages, self.map = root / "build" / "companion" / "pages", root / "build" / "companion" / "map.json"
        patched = mock.patch.multiple(gen_companion, COMPANION_DOC=self.document, COMPANION=root / "build" / "companion",
                                      BUILD=root / "build", REPO=root / "repo")
        patched.start()
        self.addCleanup(patched.stop)

    def run_main(self, strict=False):
        said = io.StringIO()
        with contextlib.redirect_stdout(said):
            count = gen_companion.main(strict)
        return count, said.getvalue()

    def page_files(self):
        return sorted(path.relative_to(self.pages).as_posix() for path in self.pages.rglob("*.md"))

    def test_pages_and_map_are_written_and_an_unchanged_page_is_left_alone(self):
        self.document.write_text("# Guide\n\n## One\n\nText.\n\n## Two\n\nText.\n", encoding="utf-8")
        count, said = self.run_main()
        self.assertEqual(count, 3)
        self.assertIn("3 pages from study.md, 0 pages that show a repository file (3 written)", said)
        self.assertEqual(self.page_files(), ["index.md", "one.md", "two.md"])
        self.assertEqual(json.loads(self.map.read_text(encoding="utf-8"))["title"], "Guide")
        self.assertIn("(0 written)", self.run_main()[1])

    def test_a_page_that_left_the_document_is_removed(self):
        self.document.write_text("# Guide\n\n## One\n\nText.\n\n## Two\n\nText.\n", encoding="utf-8")
        self.run_main()
        self.document.write_text("# Guide\n\n## One\n\nText.\n", encoding="utf-8")
        self.run_main()
        self.assertEqual(self.page_files(), ["index.md", "one.md"])

    def test_notes_are_printed(self):
        self.document.write_text("# Guide\n\nSee [this](missing.txt).\n", encoding="utf-8")
        self.assertIn("   note: line 3: the link (missing.txt) does not lead to a text file", self.run_main()[1])

    def test_a_document_that_cannot_be_cut_keeps_the_pages_of_the_last_run(self):
        self.document.write_text("# Guide\n\n## One\n\nText.\n", encoding="utf-8")
        self.run_main()
        for broken in (b"## The title is gone\n\n## One\n\nText.\n", b"\xff\xfe not saved as UTF-8"):
            with self.subTest(document=broken):
                self.document.write_bytes(broken)
                count, said = self.run_main()
                self.assertEqual(count, 0)
                self.assertIn("WARNING: the dev docs cannot be built, so it stays as it was", said)
                self.assertEqual(self.page_files(), ["index.md", "one.md"])
                self.assertTrue(self.map.is_file())

    def test_a_document_that_cannot_be_cut_stops_a_strict_run(self):
        self.document.write_text("## The title is gone\n", encoding="utf-8")
        with self.assertRaises(SystemExit) as stopped:
            self.run_main(strict=True)
        self.assertIn("The dev docs cannot be built: study.md needs exactly one title", str(stopped.exception))

    def test_without_the_document_there_is_no_second_site(self):
        self.document.write_text("# Guide\n\n## One\n\nText.\n", encoding="utf-8")
        self.run_main()
        self.document.unlink()
        count, said = self.run_main(strict=True)
        self.assertEqual(count, 0)
        self.assertIn("the dev docs is left out", said)
        self.assertFalse(self.pages.exists())
        self.assertFalse(self.map.exists())


